"use client"

import { ClipboardList, Clock, DollarSign, Package } from "lucide-react"

import { Button } from "@/components/ui/button"
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card"
import { ownerApi } from "@/lib/api/owner"
import { formatCurrency } from "@/lib/rental"
import { useApiQuery } from "@/hooks/use-api-query"
import type { MonthlyBookingPoint } from "@/lib/types/admin"
import { AdminPageHeader } from "../../admin/_components/admin-page-header"
import { MonthlyBookingsChart } from "../../admin/_components/monthly-bookings-chart"
import { StatCard } from "../../admin/_components/stat-card"
import { ErrorPanel } from "../../admin/_components/state-panels"

const statusRows: { key: "pending" | "approved" | "rejected"; label: string; color: string }[] = [
  { key: "approved", label: "Approved", color: "bg-emerald-500" },
  { key: "pending", label: "Pending", color: "bg-amber-500" },
  { key: "rejected", label: "Rejected", color: "bg-red-500" },
]

export default function OwnerAnalyticsPage() {
  const { data, loading, error, refetch } = useApiQuery(() => ownerApi.getAnalytics())

  const analytics = data

  const monthly: MonthlyBookingPoint[] = (analytics?.monthly ?? []).map(
    (point) => ({
      month: point.month,
      label: point.label,
      bookings: point.bookings ?? 0,
      revenue: point.revenue,
    })
  )

  const totalForBreakdown = analytics
    ? statusRows.reduce((sum, row) => sum + (analytics.equipmentByStatus?.[row.key] ?? 0), 0)
    : 0

  return (
    <div className="mx-auto w-full max-w-[1400px] space-y-6 p-4 sm:p-6 lg:p-8">
      <AdminPageHeader
        title="Analytics"
        description="Rental volume and revenue generated by your equipment, calculated from real database records."
        actions={
          <Button
            variant="outline"
            onClick={() => void refetch()}
            disabled={loading}
            className="gap-2"
          >
            Refresh
          </Button>
        }
      />

      {error ? <ErrorPanel message={error} onRetry={() => void refetch()} /> : null}

      <div className="grid gap-4 sm:grid-cols-2 xl:grid-cols-4">
        <StatCard
          label="Total listed equipment"
          value={analytics?.totalListings ?? 0}
          hint="Submitted by you"
          icon={Package}
          loading={loading}
        />
        <StatCard
          label="Pending equipment"
          value={analytics?.pendingEquipment ?? 0}
          hint="Waiting for admin approval"
          icon={Clock}
          tone="amber"
          loading={loading}
        />
        <StatCard
          label="Completed rentals"
          value={analytics?.completedRentals ?? 0}
          hint="Rentals your customers finished"
          icon={ClipboardList}
          tone="blue"
          loading={loading}
        />
        <StatCard
          label="Total earnings"
          value={formatCurrency(analytics?.totalEarnings ?? 0)}
          hint="Verified Stripe payments"
          icon={DollarSign}
          tone="orange"
          loading={loading}
        />
      </div>

      <div className="grid gap-4 lg:grid-cols-3">
        <Card className="lg:col-span-2">
          <CardHeader>
            <CardTitle>Monthly earnings</CardTitle>
            <CardDescription>
              Verified rental revenue for the last 12 months.
            </CardDescription>
          </CardHeader>
          <CardContent>
            <MonthlyBookingsChart data={monthly} loading={loading} />
          </CardContent>
        </Card>

        <Card>
          <CardHeader>
            <CardTitle>Equipment by status</CardTitle>
            <CardDescription>How your listings are split.</CardDescription>
          </CardHeader>
          <CardContent className="space-y-4">
            {loading
              ? Array.from({ length: 3 }).map((_, index) => (
                  <div key={index} className="space-y-2">
                    <div className="h-3 w-24 animate-pulse rounded bg-brand-navy-tint" />
                    <div className="h-2.5 w-full animate-pulse rounded-full bg-brand-navy-tint" />
                  </div>
                ))
              : statusRows.map((row) => {
                  const count = analytics?.equipmentByStatus?.[row.key] ?? 0
                  const percent =
                    totalForBreakdown > 0
                      ? Math.round((count / totalForBreakdown) * 100)
                      : 0

                  return (
                    <div key={row.key}>
                      <div className="flex items-center justify-between text-sm">
                        <span className="font-medium text-brand-navy dark:text-foreground">
                          {row.label}
                        </span>
                        <span className="text-brand-ink-soft dark:text-muted-foreground">
                          {count} · {percent}%
                        </span>
                      </div>
                      <div className="mt-2 h-2.5 overflow-hidden rounded-full bg-brand-navy-tint dark:bg-muted">
                        <div
                          className={`h-full rounded-full ${row.color}`}
                          style={{ width: `${percent}%` }}
                        />
                      </div>
                    </div>
                  )
                })}

            {!loading && totalForBreakdown === 0 ? (
              <p className="rounded-xl border border-dashed border-brand-navy-line px-4 py-6 text-center text-xs leading-5 text-brand-ink-soft dark:border-border dark:text-muted-foreground">
                No equipment has been submitted yet.
              </p>
            ) : null}
          </CardContent>
        </Card>
      </div>

      {!loading && analytics && (analytics.completedRentals ?? 0) === 0 ? (
        <p className="rounded-xl border border-dashed border-brand-navy-line px-5 py-6 text-center text-sm text-brand-ink-soft dark:border-border dark:text-muted-foreground">
          No completed rentals yet. Approved equipment will start generating
          earnings once customers book and complete rentals.
        </p>
      ) : null}
    </div>
  )
}
